use crate::register_problem;

register_problem!(
    288,
    "An enormous factorial",
    problem288
);

fn nombre_facteur(n: u128, p: u128, modulo: u128) -> u128 {
    let mut quotient = n / p;
    let mut resultat = quotient;

    while quotient >= p {
        quotient /= p;
        resultat += quotient;
        resultat %= modulo;
    }

    resultat
}

fn nf(p: u128, q: u64, n: u32) -> u128 {
    let modulo = p.pow(n);
    let mut s: u64 = 290797;

    let mut resultat = 0;

    let mut cache = vec![0u128; p as usize];
    for i in 0..=q {
        let t = (s % p as u64) as u128;
        s = (s * s) % 50515093;

        if i < n as u64 {
            resultat += nombre_facteur(t * p.pow(i as u32), p, modulo);
        } else {
            if cache[t as usize] == 0 {
                cache[t as usize] = nombre_facteur(t * modulo, p, modulo);
            }
            resultat += cache[t as usize];
        }

        resultat %= modulo;
    }

    resultat
}

/// For any prime p the number N(p,q) is defined by N(p,q) = ∑n=0 to q Tn*p**n with Tn generated by the following
/// random number generator:
///
/// S0 = 290797
/// Sn+1 = Sn² mod 50515093
/// Tn = Sn mod p
///
/// Let Nfac(p,q) be the factorial of N(p,q).
/// Let NF(p,q) be the number of factors p in Nfac(p,q).
///
/// You are given that NF(3,10000) mod 3**20=624955285.
///
/// Find NF(61,10**7) mod 61**10
pub fn problem288() -> String {
    nf(61, 10_000_000, 10).to_string()
}

